"""Check real build-script freshness and identity in isolated dependency-free Cargo fixtures."""

import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest
from unittest.mock import patch


BUILD_SCRIPT = Path(__file__).resolve().parents[1]/'crates/foveonic/build.rs'


class BuildIdentityTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        missing = [tool for tool in ('cargo', 'git') if not shutil.which(tool)]
        if missing:
            raise RuntimeError('Missing build-identity test requirements: ' + ', '.join(missing)
                               + '. Run scripts/setup_tests.py before the test suites.')

    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix='foveonic-build-identity-')
        self.addCleanup(self.temporary.cleanup)
        self.base = Path(self.temporary.name).resolve()
        self.environment = {**os.environ, 'CARGO_TARGET_DIR':str(self.base/'target'),
                            'GIT_CONFIG_NOSYSTEM':'1', 'GIT_CONFIG_GLOBAL':os.devnull}
        self.environment.pop('FOVEONIC_BUILD_REVISION', None)

    def fixture(self, root):
        source = root/'crates/foveonic/src'
        source.mkdir(parents=True)
        (root/'crates/foveonic-gui/src').mkdir(parents=True)
        (root/'crates/foveonic-gui/src/lib.rs').write_text('// watched GUI source\n')
        (root/'Cargo.toml').write_text('[workspace]\nmembers=["crates/foveonic"]\nresolver="2"\n')
        (root/'Cargo.lock').write_text('# This file is automatically @generated by Cargo.\n'
                                     '# It is not intended for manual editing.\n'
                                     'version = 4\n\n[[package]]\nname = "build-identity-fixture"\nversion = "0.0.0"\n')
        (source.parent/'Cargo.toml').write_text('[package]\nname="build-identity-fixture"\nversion="0.0.0"\nedition="2021"\n')
        (source.parent/'build.rs').write_bytes(BUILD_SCRIPT.read_bytes())
        (source/'lib.rs').write_text('pub const REVISION: &str = env!("FOVEONIC_BUILD_REVISION");\n')
        (root/'README').write_text('fixture\n')
        return root

    def git(self, root, *args):
        return subprocess.check_output(['git', '-C', str(root), *args],
                                       env=self.environment, text=True, stderr=subprocess.STDOUT).strip()

    def repository(self):
        root = self.fixture(self.base/'repository')
        self.git(root, 'init')
        self.git(root, 'symbolic-ref', 'HEAD', 'refs/heads/main')
        self.git(root, 'config', 'user.name', 'Build identity test')
        self.git(root, 'config', 'user.email', 'build-identity@example.invalid')
        self.git(root, 'config', 'core.hooksPath', str(self.base/'no-hooks'))
        self.git(root, 'config', 'core.autocrlf', 'false')
        self.git(root, 'add', '.')
        self.git(root, 'commit', '-qm', 'fixture')
        return root

    def check(self, root, *, fresh, revision, dirty, override=None):
        env = dict(self.environment)
        if override is not None:
            env['FOVEONIC_BUILD_REVISION'] = override
        result = subprocess.run(['cargo', 'check', '--offline', '--message-format=json',
                                 '--manifest-path', str(root/'Cargo.toml')],
                                cwd=root, env=env, text=True, capture_output=True, timeout=60)
        self.assertEqual(result.returncode, 0, result.stderr)
        records = [json.loads(line) for line in result.stdout.splitlines()]
        library = [row for row in records if row['reason'] == 'compiler-artifact'
                   and row['target']['kind'] == ['lib']]
        self.assertEqual(len(library), 1)
        self.assertIs(library[0]['fresh'], fresh)
        script = [row for row in records if row['reason'] == 'build-script-executed']
        self.assertEqual(len(script), 1)
        identity = dict(script[0]['env'])
        self.assertEqual(identity['FOVEONIC_BUILD_REVISION'], revision)
        self.assertEqual(identity['FOVEONIC_BUILD_DIRTY'], dirty)
        self.assertTrue(identity['FOVEONIC_BUILD_TARGET'])
        self.assertEqual(identity['FOVEONIC_BUILD_PROFILE'], 'debug')

    def test_archive_is_fresh_and_explicit_revision_changes_rebuild(self):
        root = self.fixture(self.base/'archive')
        self.check(root, fresh=False, revision='unknown', dirty='unknown')
        self.check(root, fresh=True, revision='unknown', dirty='unknown')
        self.check(root, fresh=False, revision='provided-revision', dirty='unknown', override='provided-revision')
        self.check(root, fresh=True, revision='provided-revision', dirty='unknown', override='provided-revision')

    def test_archive_inside_git_does_not_inherit_enclosing_identity(self):
        outer = self.repository()
        root = self.fixture(outer/'archive')
        self.check(root, fresh=False, revision='unknown', dirty='unknown')
        self.check(root, fresh=True, revision='unknown', dirty='unknown')

    def test_regular_checkout_stays_fresh_and_observes_ref_head_and_dirty_changes(self):
        root = self.repository()
        self.git(root, 'pack-refs', '--all', '--prune')
        first = self.git(root, 'rev-parse', 'HEAD')
        self.check(root, fresh=False, revision=first, dirty='false')
        self.check(root, fresh=True, revision=first, dirty='false')
        self.git(root, 'commit', '--allow-empty', '-qm', 'next')
        second = self.git(root, 'rev-parse', 'HEAD')
        self.assertNotEqual(first, second)
        self.check(root, fresh=False, revision=second, dirty='false')
        self.check(root, fresh=True, revision=second, dirty='false')
        self.git(root, 'checkout', '--detach', first)
        self.check(root, fresh=False, revision=first, dirty='false')
        with (root/'crates/foveonic/src/lib.rs').open('a') as stream:
            stream.write('// changed source\n')
        self.check(root, fresh=False, revision=first, dirty='true')
        self.check(root, fresh=True, revision=first, dirty='true')
        (root/'README').write_text('staged metadata change\n')
        self.git(root, 'add', 'README')
        self.check(root, fresh=False, revision=first, dirty='true')
        self.check(root, fresh=True, revision=first, dirty='true')

    def test_linked_worktree_uses_real_metadata_and_observes_branch_commits(self):
        main = self.repository()
        root = self.base/'linked'
        self.git(main, 'worktree', 'add', '-b', 'linked', str(root))
        self.assertTrue((root/'.git').is_file())
        first = self.git(root, 'rev-parse', 'HEAD')
        self.check(root, fresh=False, revision=first, dirty='false')
        self.check(root, fresh=True, revision=first, dirty='false')
        self.git(root, 'commit', '--allow-empty', '-qm', 'linked next')
        second = self.git(root, 'rev-parse', 'HEAD')
        self.assertNotEqual(first, second)
        self.check(root, fresh=False, revision=second, dirty='false')
        self.check(root, fresh=True, revision=second, dirty='false')


class BuildIdentityRequirementsTests(unittest.TestCase):
    def test_missing_tools_fail_clearly_instead_of_skipping_fixtures(self):
        for missing in ({'cargo'}, {'git'}, {'cargo', 'git'}):
            with self.subTest(missing=missing), \
                    patch.object(shutil, 'which', side_effect=lambda tool: None if tool in missing else '/tool'), \
                    self.assertRaisesRegex(RuntimeError, 'Missing build-identity test requirements:') as error:
                BuildIdentityTests.setUpClass()
            self.assertIn('scripts/setup_tests.py', str(error.exception))
            for tool in missing:
                self.assertIn(tool, str(error.exception))


if __name__ == '__main__':
    unittest.main()
